import { createExercise, createPause, createInitialState, sanitizeState, duplicateStep } from '../js/models.js';
import { totalDuration, routineProgress } from '../js/utils.js';
import { RoutinePlayer } from '../js/routine-player.js';
import { RoutineEditor } from '../js/routine-editor.js';

function assert(value, message) { if (!value) throw new Error(message); }
const state = createInitialState();
const repetition = createExercise({ mode: 'repetitions', repetitions: 12 });
state.routines[0].steps = [repetition, createPause({ duration: 8 })];
state.settings.secondsPerRepetition = 2;
const clean = sanitizeState(state);
const routine = clean.routines[0];
assert(totalDuration(routine, clean.settings) === 32, 'Il totale deve includere la stima configurata.');
assert(totalDuration(routine) === 20, 'La stima predefinita deve essere un secondo per ripetizione.');
assert(routineProgress(routine, 0, 999, clean.settings) === 0, 'Le ripetizioni attendono Fatto.');
assert(routineProgress(routine, 1, 0, clean.settings) === 0.75, 'Fatto deve accreditare la durata stimata.');
assert(duplicateStep(repetition).repetitions === 12, 'La duplicazione deve conservare le ripetizioni.');
assert(sanitizeState({ schemaVersion: 1, routines: [], settings: {} }).settings.secondsPerRepetition === 1, 'I backup precedenti devono ricevere il default.');
const editor = new RoutineEditor({}, routine, {}, clean.settings);
assert(editor.stepMarkup(repetition, 0).includes('data-field="repetitions"'), 'Editor ripetizioni assente.');
assert(!editor.stepMarkup(repetition, 0).includes('data-field="minutes"'), 'Le ripetizioni non devono mostrare la durata.');
const player = new RoutinePlayer({}, routine, clean.settings);
let started = 0;
let stopped = 0;
player.engine.start = () => started++;
player.engine.stop = () => stopped++;
player.announcer = {};
player.updateTimer = () => {};
player.updateToggleControl = () => {};
player.requestWakeLock = () => {};
player.startStep();
assert(started === 0 && stopped === 1, 'Un esercizio a ripetizioni non deve avviare un timer.');
let destination;
player.playStepTransitionCue = () => {};
player.goToStep = (index) => { destination = index; };
player.togglePause();
assert(destination === 1, 'Fatto deve passare allo step successivo.');
player.currentStepIndex = 1;
player.startStep();
assert(started === 1, 'La pausa successiva deve avviare il timer.');
print('Esercizi a ripetizioni: OK');
